#!/usr/bin/env bash
# runs the unchanged terraform/ code against LocalStack (an AWS API emulator in docker) for when
# there's no AWS account. only the provider endpoint changes, through a temporary *_override.tf,
# and state lives in a separate "localstack" workspace so it can never mix with real AWS state.
#
#   ./scripts/terraform-localstack.sh plan                        # full plan: VPC + EKS (62 resources)
#   ./scripts/terraform-localstack.sh apply -target=module.vpc    # VPC, 2 public + 2 private subnets, NAT, routes
#   ./scripts/terraform-localstack.sh apply                       # + IAM/KMS/SGs, stops at EKS CreateCluster
#                                                                 #   (EKS isn't emulated in the free edition)
#   ./scripts/terraform-localstack.sh destroy
#   ./scripts/terraform-localstack.sh aws ec2 describe-vpcs       # aws cli pointed at the emulator
#   ./scripts/terraform-localstack.sh down                        # stop + remove the emulator
set -euo pipefail
cd "$(dirname "$0")/../terraform"

# last community release that runs without an account token (newer tags need LOCALSTACK_AUTH_TOKEN)
IMAGE=localstack/localstack:4.14
ENDPOINT=http://localhost:4566
export AWS_ACCESS_KEY_ID=test AWS_SECRET_ACCESS_KEY=test AWS_DEFAULT_REGION=ap-south-1

case "${1:-}" in
  down) docker rm -f localstack >/dev/null && echo "localstack removed"; exit 0 ;;
  aws)  shift; exec aws --endpoint-url "$ENDPOINT" "$@" ;;
  "")   sed -n '2,13p' "$0"; exit 1 ;;
esac

if ! curl -sf "$ENDPOINT/_localstack/health" >/dev/null; then
  docker start localstack >/dev/null 2>&1 || docker run -d --name localstack -p 127.0.0.1:4566:4566 "$IMAGE" >/dev/null
  echo -n "waiting for localstack"
  until curl -sf "$ENDPOINT/_localstack/health" >/dev/null; do echo -n .; sleep 2; done; echo
fi

# on exit: drop the override and switch back to the default workspace, so a plain
# `terraform plan` afterwards talks to real AWS with real state, never this one
trap 'rm -f localstack_override.tf; terraform workspace select default >/dev/null 2>&1 || true' EXIT
cat > localstack_override.tf <<HCL
# generated by scripts/terraform-localstack.sh, deleted when it exits
provider "aws" {
  region                      = var.aws_region
  access_key                  = "test"
  secret_key                  = "test"
  skip_credentials_validation = true
  skip_metadata_api_check     = true
  skip_requesting_account_id  = true

  endpoints {
    ec2  = "$ENDPOINT"
    eks  = "$ENDPOINT"
    iam  = "$ENDPOINT"
    sts  = "$ENDPOINT"
    kms  = "$ENDPOINT"
    logs = "$ENDPOINT"
  }
}
HCL

terraform init -input=false >/dev/null
terraform workspace select -or-create localstack >/dev/null
terraform "$@"
